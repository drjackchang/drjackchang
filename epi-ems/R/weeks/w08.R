## ---- 期中複習 1：陰性預測值
#' 某到院前中風量表敏感度 80%、特異度 90%，在疑似中風個案中真正中風的盛行率為 10%。用 1,000 人的假想族群算 NPV。
N <- 1000; prev <- .10; se <- .80; sp <- .90
TP <- N * prev * se; FN <- N * prev - TP
TN <- N * (1 - prev) * sp; FP <- N * (1 - prev) - TN
c(PPV = TP / (TP + FP), NPV = TN / (TN + FN))

## ---- 期中複習 2：發生密度（人時）
#' 10 位消防員追蹤 4 年，事件皆發生在年中。人年：追蹤到事件／設限為止的年數加總。
followup <- c(4, 2.5, 4, 1.5, 4, 3.5, 4, 0.5, 4, 2.5)   # 年
events   <- c(0, 1, 0, 1, 0, 1, 0, 0, 0, 1)            # 1 = 發生心血管事件
sum(events) / sum(followup)

## ---- 期中複習 3：致死率與死亡率
